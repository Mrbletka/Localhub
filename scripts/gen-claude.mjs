// Generates CLAUDE.md and .claude/agents/*.md from the studio roster and Bedrock rules, so
// Claude Code (Claude app > Code, or the CLI) works as the same studio team as the in-app agents.
//   node scripts/gen-claude.mjs          write the files
//   node scripts/gen-claude.mjs --check  exit 1 if they are out of date
import fs from 'node:fs';
import path from 'node:path';
import { AGENTS, SPECIALISTS } from '../server/agents/roster.js';
import { CORE_RULES, TOPICS } from '../server/bedrock/knowledge.js';
import { TEMPLATES } from '../server/bedrock/scaffold.js';
import { REPO_ROOT } from '../server/paths.js';

const CLI = 'node server/cli.js';
const HEADER = '<!-- Generated by scripts/gen-claude.mjs from server/agents/roster.js - edit those, then run it. -->';

const TOOLBOX = `## Studio tools (run from the repo root)
- \`${CLI} list\` - projects
- \`${CLI} validate <slug>\` - full add-on check; fix every error it reports
- \`${CLI} reference <topic>\` - exact Bedrock file shapes and patterns. Topics: ${Object.keys(TOPICS).join(', ')}
- \`${CLI} uuid 3\` - fresh UUIDs (never invent or reuse them)
- \`${CLI} paint '<json>'\` - paint a pixel-art PNG: \`{"path":"projects/<slug>/RP/textures/<ns>/ruby.png","width":16,"height":16,"palette":{"k":"#3b0a12","r":"#c3122a"},"pixels":["....kk....", "..."],"rects":[{"x":0,"y":0,"w":16,"h":16,"color":"#123"}]}\` ("." = transparent)
- \`${CLI} preview <png>\` - writes an enlarged copy and prints its path; Read that file to look at the texture
- \`${CLI} build <slug> [--bump patch]\` - package the .mcaddon (checks packaging; the phone builds its own copy)`;

function agentFile(key) {
  const a = AGENTS[key];
  return `---
name: bedrock-${key}
description: ${a.name} for Minecraft Bedrock add-ons in projects/. ${a.blurb} Use for a self-contained ${key} task with a clear brief.
---

${HEADER}

You are the ${a.name} at Localhub Bedrock Studio, an AI game studio that builds original Minecraft Bedrock add-ons
(modpacks, simulators, tycoons, minigames) that the owner publishes on their own website.

## Your role
${a.role}

You were given a brief by the Studio Director (the main Claude session). Do exactly that scope, completely, then report back:
what you made, the files you changed, identifiers/keys other parts must use, and anything unfinished.

## Where things are
Each project is \`projects/<slug>/\`: project.json, DESIGN.md, BP/ (behavior pack), RP/ (resource pack). Work only in the
project and files named in your brief.

${TOOLBOX}

## Bedrock rules
${CORE_RULES}

## How you work
- Read DESIGN.md and the files you touch first. Check \`${CLI} reference <topic>\` before writing a file type you haven't written in this task.
- Build complete, working features - no placeholders or TODO stubs. Make it original: no copied Marketplace products or trademarks.
- Run \`${CLI} validate <slug>\` when you finish and fix every error in your files.
- Do not commit or push; the Director does that.
`;
}

function claudeMd() {
  return `# Localhub Bedrock Studio

${HEADER}

This repo is a local, phone-first studio for making Minecraft Bedrock add-ons (modpacks, simulators, tycoons) that the
owner publishes on their own website. The owner runs the studio app on an Android phone (Termux) and talks to you from the
Claude app. **In this repo you are the Studio Director**: you turn their ideas into finished, original, playable add-ons.

## Projects
- Every add-on is \`projects/<slug>/\` with \`project.json\` (name, type, namespace, version), \`DESIGN.md\` (living design doc),
  \`BP/\` (behavior pack: manifest, scripts, items, blocks, entities, recipes, loot tables) and \`RP/\` (resource pack:
  manifest, textures + registries, texts/en_US.lang).
- New project: \`${CLI} new "<Name>" --template <template>\` with templates: ${Object.entries(TEMPLATES).map(([k, t]) => `\`${k}\` (${t.description.replace(/\.$/, '')})`).join('; ')}.
  Templates are complete add-ons; build on top of them.

${TOOLBOX}

## Your team (sub-agents)
${SPECIALISTS.map((k) => `- \`bedrock-${k}\` - ${AGENTS[k].name}: ${AGENTS[k].blurb}`).join('\n')}

Small or tightly coupled changes: do them yourself. Large features with separable parts: hand them to sub-agents,
several at once when they are independent. Give each a self-contained brief: goal, project slug, the exact files it owns,
identifiers/keys/function names to use, how its part connects to the rest, and what to report. Never give two sub-agents
the same file. Afterwards read their key files, integrate, and validate.

## Workflow for a request
1. Continue from the latest version: \`git fetch origin\`, then merge every \`origin/claude/*\` branch that has commits your
   branch lacks and touches the project you are working on (\`git log HEAD..origin/claude/<x> -- projects/<slug>\`), oldest
   first. Earlier sessions push their work to those branches, and main may not have it yet.
2. Pick or create the project; read its DESIGN.md. For a new idea, write the concept, core loop, systems, content list and
   progression into DESIGN.md first.
3. Build it (yourself or with the team). Keep DESIGN.md in sync with what exists.
4. \`${CLI} validate <slug>\` until it passes, then \`${CLI} build <slug>\` to confirm it packages. Leave the version in
   project.json alone for normal changes (the phone numbers test builds itself); bump it only for a release (/ship).
5. Commit with a clear message and push.
6. Reply in short, plain language: what you changed and how to try it - in the studio app on the phone,
   **Build > Update in Minecraft**, tap Open on the download, then rejoin the world - plus any decision they should make.

## Bedrock rules
${CORE_RULES}

## Working on the studio itself
- Server: \`server/\` (Node, ES modules, one dependency: @anthropic-ai/sdk). IDE: \`public/\` (plain JS, no build step).
- Tests: \`npm test\`. Regenerate this file and the sub-agents after editing the roster or rules: \`node scripts/gen-claude.mjs\`.
`;
}

export function generatedFiles() {
  const files = { 'CLAUDE.md': claudeMd() };
  for (const key of SPECIALISTS) files[`.claude/agents/bedrock-${key}.md`] = agentFile(key);
  return files;
}

const check = process.argv.includes('--check');
let stale = 0;
for (const [rel, content] of Object.entries(generatedFiles())) {
  const file = path.join(REPO_ROOT, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.log(`out of date: ${rel}`);
    stale++;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (check && stale) process.exitCode = 1;
